-- Smart Journey 초기 스키마
-- PostgreSQL 17 과 H2(PostgreSQL 모드) 양쪽에서 돌도록 표준 SQL 위주로 작성한다.
-- 정책 4: 위치 좌표·이동 궤적·VIN 은 저장하지 않는다. (store 의 좌표는 매장 위치라 해당 없음)

-- 매장 -----------------------------------------------------------------------
create table store (
    id                  bigint generated by default as identity primary key,
    name                varchar(100)     not null,
    address             varchar(255)     not null,
    -- NaviHelper RouteInfo / RequestWaypointInfo 에 그대로 넣을 값
    latitude            double precision not null,
    longitude           double precision not null,
    poi_id              varchar(100),
    poi_sub_id          varchar(20)      not null default '0',
    -- 대기시간 산출: manual_wait_min ?: (앞 팀 수 × minutes_per_team)
    minutes_per_team    int              not null default 5,
    arrival_buffer_min  int              not null default 10,
    manual_wait_min     int,
    max_defers          int              not null default 2,
    avg_stay_min        int              not null default 60,
    open_time           time,
    close_time          time,
    pos_pin_hash        varchar(100)     not null,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null
);

-- 차량(기기) — 동의 시 발급하는 임의 토큰으로만 식별한다 (가명 처리) --------------
create table device (
    id                  bigint generated by default as identity primary key,
    device_token        varchar(64)  not null unique,
    consent_version     varchar(20)  not null,
    consented_at        timestamp with time zone not null,
    revoked_at          timestamp with time zone,
    last_seen_at        timestamp with time zone,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null
);

-- 여정(코스) ------------------------------------------------------------------
create table journey (
    id                  bigint generated by default as identity primary key,
    device_id           bigint       not null references device (id),
    party_size          int          not null,
    party_source        varchar(10)  not null,  -- SENSOR / MANUAL
    status              varchar(10)  not null,  -- ACTIVE / ENDED
    started_at          timestamp with time zone not null,
    ended_at            timestamp with time zone,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null
);
create index idx_journey_device_status on journey (device_id, status);

create table journey_stop (
    id                  bigint generated by default as identity primary key,
    journey_id          bigint       not null references journey (id),
    store_id            bigint       not null references store (id),
    seq                 int          not null,  -- 1..3 (경유지 최대 2 + 목적지 1)
    planned_stay_min    int,
    status              varchar(10)  not null,  -- PLANNED / WAITING / DONE / SKIPPED
    waiting_id          bigint,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    constraint uk_journey_stop_seq unique (journey_id, seq)
);

-- 웨이팅(대기열 한 팀) ----------------------------------------------------------
create table waiting (
    id                  bigint generated by default as identity primary key,
    store_id            bigint       not null references store (id),
    journey_id          bigint references journey (id),
    device_id           bigint references device (id),
    channel             varchar(10)  not null,  -- VEHICLE / WALK_IN
    business_date       date         not null,
    ticket_no           int          not null,
    party_size          int          not null,
    status              varchar(12)  not null,  -- REGISTERED / ARRIVED / CALLED / SEATED / NO_SHOW / CANCELLED
    queue_order         bigint       not null,  -- 작을수록 앞. 순번 미루기는 이 값을 뒤로 옮긴다
    defer_count         int          not null default 0,
    approval_method     varchar(10),            -- TOUCH / VOICE (차량 채널만)
    eta_min             int,
    eta_updated_at      timestamp with time zone,
    registered_at       timestamp with time zone not null,
    called_at           timestamp with time zone,
    closed_at           timestamp with time zone,
    version             bigint       not null default 0,
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    constraint uk_waiting_ticket unique (store_id, business_date, ticket_no)
);
create index idx_waiting_store_status on waiting (store_id, status, queue_order);
create index idx_waiting_device on waiting (device_id);

-- 도착·하차 확인 결과 -----------------------------------------------------------
create table arrival_check (
    id                  bigint generated by default as identity primary key,
    waiting_id          bigint       not null references waiting (id),
    result              varchar(12)  not null,  -- CONFIRMED / MANUAL / UNCONFIRMED
    alighted            int,                    -- M (UNCONFIRMED 면 null)
    party_size          int          not null,  -- N
    arrived_at          timestamp with time zone not null,
    door_opened_at      timestamp with time zone,
    door_locked_at      timestamp with time zone,
    belt_released_at    timestamp with time zone,
    settled_at          timestamp with time zone,
    occupancy_before    int,
    occupancy_after     int,
    created_at          timestamp with time zone not null
);
create index idx_arrival_waiting on arrival_check (waiting_id);

-- 감사 로그 · 지표 산출용 이벤트 -------------------------------------------------
create table waiting_event (
    id                  bigint generated by default as identity primary key,
    waiting_id          bigint       not null references waiting (id),
    type                varchar(30)  not null,
    payload             varchar(4000),
    occurred_at         timestamp with time zone not null
);
create index idx_waiting_event_waiting on waiting_event (waiting_id, occurred_at);

-- 차량 쪽에서만 일어나는 일(승인 카드 노출·거절, 인원 제안 수락 등) — KPI 용 -------------
create table journey_event (
    id                  bigint generated by default as identity primary key,
    journey_id          bigint       not null references journey (id),
    store_id            bigint,
    type                varchar(30)  not null,
    payload             varchar(4000),
    occurred_at         timestamp with time zone not null
);
create index idx_journey_event_journey on journey_event (journey_id, occurred_at);

-- 접수 중복 방지 (Idempotency-Key) ----------------------------------------------
create table idempotency_record (
    id                  bigint generated by default as identity primary key,
    device_id           bigint       not null references device (id),
    idem_key            varchar(64)  not null,
    request_hash        varchar(64)  not null,
    status_code         int          not null,
    response_body       varchar(4000) not null,
    created_at          timestamp with time zone not null,
    constraint uk_idempotency unique (device_id, idem_key)
);
